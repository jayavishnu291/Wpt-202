/**
 * Expo config plugin: turns OFF every kind of Android backup for app data (BR-PR-05, FR-PR-08).
 *
 * What it does at `npx expo prebuild` time:
 *   1. Writes res/xml/wpt_data_extraction_rules.xml  (Android 12+: cloud backup AND device-to-device transfer)
 *   2. Writes res/xml/wpt_full_backup_rules.xml      (Android 10-11: full backup)
 *   3. Sets on <application>: allowBackup="false", dataExtractionRules, fullBackupContent
 *
 * Never edit the android/ folder by hand. It is regenerated.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];
const DEVICE_DOMAINS = ['device_root', 'device_file', 'device_database', 'device_sharedpref'];

function excludeLines(domains, indent) {
  return domains.map((domain) => `${indent}<exclude domain="${domain}" path="." />`).join('\n');
}

const DATA_EXTRACTION_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js. Nothing is backed up or transferred. -->
<data-extraction-rules>
  <cloud-backup>
${excludeLines([...DOMAINS, ...DEVICE_DOMAINS], '    ')}
  </cloud-backup>
  <device-transfer>
${excludeLines([...DOMAINS, ...DEVICE_DOMAINS], '    ')}
  </device-transfer>
</data-extraction-rules>
`;

const FULL_BACKUP_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js. Nothing is backed up. -->
<full-backup-content>
${excludeLines([...DOMAINS, ...DEVICE_DOMAINS], '  ')}
</full-backup-content>
`;

function withBackupXmlFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const xmlDir = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app', 'src', 'main', 'res', 'xml',
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'wpt_data_extraction_rules.xml'), DATA_EXTRACTION_XML);
      fs.writeFileSync(path.join(xmlDir, 'wpt_full_backup_rules.xml'), FULL_BACKUP_XML);
      return modConfig;
    },
  ]);
}

function withBackupManifest(config) {
  return withAndroidManifest(config, (modConfig) => {
    const manifest = modConfig.modResults.manifest;
    manifest.$ = manifest.$ ?? {};
    manifest.$['xmlns:tools'] = 'http://schemas.android.com/tools';

    const application = manifest.application?.[0];
    if (!application) throw new Error('Android manifest has no <application> element.');

    application.$['android:allowBackup'] = 'false';
    application.$['android:dataExtractionRules'] = '@xml/wpt_data_extraction_rules';
    application.$['android:fullBackupContent'] = '@xml/wpt_full_backup_rules';

    // If a library also sets these, ours wins.
    const replace = new Set((application.$['tools:replace'] ?? '').split(',').filter(Boolean));
    ['android:allowBackup', 'android:dataExtractionRules', 'android:fullBackupContent']
      .forEach((name) => replace.add(name));
    application.$['tools:replace'] = [...replace].join(',');

    return modConfig;
  });
}

module.exports = function withBackupRules(config) {
  return withBackupManifest(withBackupXmlFiles(config));
};
